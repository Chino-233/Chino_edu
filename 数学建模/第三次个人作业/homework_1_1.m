% 求解线性规划问题
% max z=3x1-x2-x3
% s.t. x1-2x2+x3<=11
%      -4x1+x2+2x3>=3
%      -2x1+x3=1
%      x1,x2,x3>=0

% 定义目标函数系数（取负值，将最大化问题转换为最小化问题）
f = [-3; 1; 1];

% 定义不等式约束 A*x <= b
A = [1, -2, 1;    % x1-2x2+x3<=11
     4, -1, -2];  % 对 -4x1+x2+2x3>=3 取反得 4x1-x2-2x3<=-3
b = [11; -3];

% 定义等式约束 Aeq*x = beq
Aeq = [-2, 0, 1]; % -2x1+x3=1
beq = 1;

% 定义变量的下限
lb = [0; 0; 0];   % x1,x2,x3>=0

% 求解线性规划问题
[x, fval] = linprog(f, A, b, Aeq, beq, lb);

% 输出结果
fprintf('最优解：\n');
fprintf('x1 = %.4f\n', x(1));
fprintf('x2 = %.4f\n', x(2));
fprintf('x3 = %.4f\n', x(3));
fprintf('目标函数的最优值 z = %.4f\n', -fval); % 注意要取负值，因为求解的是最大化问题